-- H2 本地文件数据库初始化脚本。
-- base-0：EVOPS 初始工作区
-- exam-1：考试机构考场与准考证建档工作区（报名 / 编排 / 发证 / 查档）
-- grade-1：出分落级与复核窗口（等级规则带版本 / 窗口随批次配置 / 复核超窗自动关闭 / 改分留痕通知）

CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

-- ============ 考点 ============
CREATE TABLE IF NOT EXISTS t_exam_site (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    address VARCHAR(255),
    contact_person VARCHAR(64),
    contact_phone VARCHAR(32),
    status VARCHAR(16) NOT NULL DEFAULT 'ENABLED',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_exam_site_code UNIQUE (code)
);

-- ============ 考场（归属考点，容量、位置记全） ============
CREATE TABLE IF NOT EXISTS t_exam_room (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL,
    room_no VARCHAR(32) NOT NULL,
    building VARCHAR(64),
    floor_no INT,
    capacity INT NOT NULL,
    location_desc VARCHAR(255),
    status VARCHAR(16) NOT NULL DEFAULT 'ENABLED',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_exam_room_site_no UNIQUE (site_id, room_no),
    CONSTRAINT ck_exam_room_capacity CHECK (capacity > 0)
);

-- ============ 考试批次 ============
CREATE TABLE IF NOT EXISTS t_exam_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    site_id BIGINT NOT NULL,
    subject VARCHAR(128),
    exam_date DATE,
    start_time TIME,
    end_time TIME,
    -- CREATED 建档 / ARRANGED 已编排 / FINALIZED 已办结
    status VARCHAR(16) NOT NULL DEFAULT 'CREATED',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_exam_batch_code UNIQUE (code)
);

-- ============ 报名名册 ============
CREATE TABLE IF NOT EXISTS t_registration (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_no VARCHAR(40) NOT NULL,
    name VARCHAR(64) NOT NULL,
    id_type VARCHAR(16) NOT NULL DEFAULT 'ID_CARD',
    id_no VARCHAR(32),
    gender VARCHAR(8),
    phone VARCHAR(32),
    batch_id BIGINT NOT NULL,
    subject VARCHAR(128),
    -- REGISTERED 已报名 / ARRANGED 已编排
    status VARCHAR(16) NOT NULL DEFAULT 'REGISTERED',
    correction_count INT NOT NULL DEFAULT 0,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_registration_reg_no UNIQUE (reg_no)
);
CREATE INDEX IF NOT EXISTS idx_registration_name ON t_registration (name);
CREATE INDEX IF NOT EXISTS idx_registration_batch ON t_registration (batch_id);

-- ============ 名册勘误（只追加，旧值留痕，不覆盖历史） ============
CREATE TABLE IF NOT EXISTS t_registration_correction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_id BIGINT NOT NULL,
    field_name VARCHAR(32) NOT NULL,
    field_label VARCHAR(64),
    old_value VARCHAR(255),
    new_value VARCHAR(255),
    reason VARCHAR(255),
    operator VARCHAR(64),
    corrected_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_correction_reg ON t_registration_correction (registration_id);

-- ============ 准考证（证号全局唯一；批次内考场+座位唯一） ============
CREATE TABLE IF NOT EXISTS t_admission_ticket (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_no VARCHAR(40) NOT NULL,
    registration_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    site_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    seat_no INT NOT NULL,
    -- PENDING 待打印 / PRINTED 已打印 / ISSUED 已发放
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    printed_by VARCHAR(64),
    printed_at TIMESTAMP,
    issued_by VARCHAR(64),
    issued_at TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_ticket_no UNIQUE (ticket_no),
    CONSTRAINT uk_ticket_registration UNIQUE (registration_id),
    CONSTRAINT uk_ticket_seat UNIQUE (batch_id, room_id, seat_no),
    CONSTRAINT ck_ticket_seat CHECK (seat_no > 0)
);
CREATE INDEX IF NOT EXISTS idx_ticket_batch ON t_admission_ticket (batch_id);

-- ============ 阶段结果（与最终结论分表保存） ============
CREATE TABLE IF NOT EXISTS t_stage_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    -- IMPORT 报名导入 / ARRANGEMENT 编排 / PRINTING 打印 / ISSUANCE 发放
    stage VARCHAR(16) NOT NULL,
    affected_count INT NOT NULL DEFAULT 0,
    detail CLOB,
    operator VARCHAR(64),
    executed_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_stage_batch ON t_stage_result (batch_id);

-- ============ 最终结论 ============
CREATE TABLE IF NOT EXISTS t_final_conclusion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    conclusion_code VARCHAR(32) NOT NULL,
    summary VARCHAR(512),
    total_count INT NOT NULL DEFAULT 0,
    printed_count INT NOT NULL DEFAULT 0,
    issued_count INT NOT NULL DEFAULT 0,
    operator VARCHAR(64),
    concluded_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_final_conclusion_batch UNIQUE (batch_id)
);

-- ============ 工作区版本（版本选择 / 状态回退可追溯） ============
CREATE TABLE IF NOT EXISTS t_workspace_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(40) NOT NULL,
    label VARCHAR(128) NOT NULL,
    -- SNAPSHOT 快照 / ROLLBACK 回退生成
    kind VARCHAR(16) NOT NULL DEFAULT 'SNAPSHOT',
    restored_from_version VARCHAR(40),
    -- 同一时刻只有一个当前版本
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    snapshot CLOB,
    remark VARCHAR(255),
    operator VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_workspace_version_no UNIQUE (version_no)
);

-- 工作区版本事件（CREATE/SELECT/ROLLBACK 全程留痕；回退不清此表）
CREATE TABLE IF NOT EXISTS t_workspace_version_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    version_no VARCHAR(40) NOT NULL,
    action VARCHAR(16) NOT NULL,
    detail VARCHAR(512),
    operator VARCHAR(64),
    event_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_version_event_version ON t_workspace_version_event (version_id);

-- ============ grade-1：出分落级与复核窗口 ============

-- 等级规则模块（归属项目，本批次先跑助考项目 ASSIST）
CREATE TABLE IF NOT EXISTS t_grade_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    project_code VARCHAR(32) NOT NULL DEFAULT 'ASSIST',
    -- DRAFT 草稿 / ENABLED 启用（有生效版本） / DISABLED 停用
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    current_version_id BIGINT,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_grade_rule_code UNIQUE (code)
);

-- 等级规则版本（规则带版本：只追加，发布后冻结，永不删改）
CREATE TABLE IF NOT EXISTS t_grade_rule_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id BIGINT NOT NULL,
    version_no INT NOT NULL,
    -- DRAFT 草稿 / EFFECTIVE 生效中 / ARCHIVED 已归档（被新版本顶替）
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    min_score INT NOT NULL,
    max_score INT NOT NULL,
    bands_json CLOB NOT NULL,
    published_by VARCHAR(64),
    published_at TIMESTAMP,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_grade_rule_version UNIQUE (rule_id, version_no),
    CONSTRAINT ck_grade_rule_score_range CHECK (min_score >= 0 AND max_score >= min_score)
);
CREATE INDEX IF NOT EXISTS idx_grade_rule_version_rule ON t_grade_rule_version (rule_id);

-- 批次等级与复核窗口配置（窗口起止跟批次走，不写死）
CREATE TABLE IF NOT EXISTS t_grade_batch_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    project_code VARCHAR(32) NOT NULL DEFAULT 'ASSIST',
    rule_id BIGINT,
    -- NOT_STARTED 未开始 / OPEN 窗口期 / CLOSED 已关闭（含超窗自动关闭）
    window_status VARCHAR(16) NOT NULL DEFAULT 'NOT_STARTED',
    score_release_at TIMESTAMP,
    window_start_at TIMESTAMP,
    window_end_at TIMESTAMP,
    auto_closed BOOLEAN NOT NULL DEFAULT FALSE,
    closed_by VARCHAR(64),
    closed_at TIMESTAMP,
    close_reason VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_grade_batch_config_batch UNIQUE (batch_id)
);

CREATE INDEX IF NOT EXISTS idx_grade_batch_config_rule ON t_grade_batch_config (rule_id);

-- 学员成绩（卷面分按生效版本分数段落等级；一人一批次一条，当前态）
CREATE TABLE IF NOT EXISTS t_score_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    registration_id BIGINT NOT NULL,
    raw_score INT NOT NULL,
    grade_level VARCHAR(16) NOT NULL,
    grade_label VARCHAR(64),
    rule_version_id BIGINT NOT NULL,
    -- RELEASED 已出分 / UPDATED 复核改分后（重新出分也落此态，前后值进 change_log）
    status VARCHAR(16) NOT NULL DEFAULT 'RELEASED',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_score_record_unique UNIQUE (batch_id, registration_id),
    CONSTRAINT ck_score_record_range CHECK (raw_score >= 0)
);
CREATE INDEX IF NOT EXISTS idx_score_record_batch ON t_score_record (batch_id);
CREATE INDEX IF NOT EXISTS idx_score_record_reg ON t_score_record (registration_id);

-- 改分痕迹（只追加；出分落级与复核改分前后都留痕）
CREATE TABLE IF NOT EXISTS t_score_change_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    score_record_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    registration_id BIGINT NOT NULL,
    change_type VARCHAR(16) NOT NULL,
    old_raw_score INT,
    old_grade_level VARCHAR(16),
    new_raw_score INT,
    new_grade_level VARCHAR(16),
    rule_version_id BIGINT,
    review_id BIGINT,
    reason VARCHAR(255),
    operator VARCHAR(64),
    changed_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_score_change_log_record ON t_score_change_log (score_record_id);
CREATE INDEX IF NOT EXISTS idx_score_change_log_review ON t_score_change_log (review_id);

-- 复核申请（窗口期内可提，超窗自动关闭；一人一批次一次在办）
CREATE TABLE IF NOT EXISTS t_review_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    score_record_id BIGINT NOT NULL,
    registration_id BIGINT NOT NULL,
    -- SUBMITTED 已提交 / PROCESSING 受理中 / CONFIRMED 维持原判 / CHANGED 复核改分 /
    -- REJECTED 不予受理。窗口关闭只拦新申请，窗内已提交的在办申请仍可结论。
    status VARCHAR(20) NOT NULL DEFAULT 'SUBMITTED',
    request_reason VARCHAR(255),
    contact_phone VARCHAR(32),
    final_score INT,
    final_grade_level VARCHAR(16),
    final_grade_label VARCHAR(64),
    conclusion_remark VARCHAR(255),
    concluded_by VARCHAR(64),
    concluded_at TIMESTAMP,
    notified_at TIMESTAMP,
    window_start_at TIMESTAMP,
    window_end_at TIMESTAMP,
    submitted_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
-- 在办唯一（SUBMITTED/PROCESSING 同一学员同批次仅一条）由服务层校验；
-- 终态可多次申请，故此处不加数据库唯一约束。
CREATE INDEX IF NOT EXISTS idx_review_active ON t_review_request (batch_id, registration_id, status);
CREATE INDEX IF NOT EXISTS idx_review_batch ON t_review_request (batch_id);
CREATE INDEX IF NOT EXISTS idx_review_record ON t_review_request (score_record_id);
CREATE INDEX IF NOT EXISTS idx_review_status ON t_review_request (status);

-- 出分 / 复核通知（结论回写即通知；无外发渠道先落库，待接入短信/站内信）
CREATE TABLE IF NOT EXISTS t_grade_notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    registration_id BIGINT NOT NULL,
    review_id BIGINT,
    score_record_id BIGINT,
    -- SCORE_RELEASED 出分通知 / REVIEW_RECEIVED 已受理 / REVIEW_CONCLUDED 复核结论通知 / WINDOW_CLOSED 窗口关闭
    category VARCHAR(20) NOT NULL,
    title VARCHAR(128) NOT NULL,
    content VARCHAR(1000),
    -- PENDING 待外发 / SENT 已发送（当前版本写完即视为可通知）
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    phone VARCHAR(32),
    operator VARCHAR(64),
    sent_at TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_grade_notification_reg ON t_grade_notification (registration_id);
CREATE INDEX IF NOT EXISTS idx_grade_notification_review ON t_grade_notification (review_id);

